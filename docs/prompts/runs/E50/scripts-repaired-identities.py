"""
E50 (Entry 163): the generator of `tools/content/repaired_identities.json`, the reviewed musical repairs whose old
identity the repaired file carries for learner continuity (the reviewer's conditional approval,
`responses/questions-bd7d303e.md` §4: "explicitly add the seven old identities to the repaired files' compatibility
relation"). Never edited by hand.

    python scripts-repaired-identities.py --record <base sha> [<served content dir>]

For each of the seven rows:
  1. the old file is the committed file at <base sha> (`git show <base>:content/scores/pdmx/<cid>.mxl`, read only),
     the file every catalogue since D4 served; where <served content dir> is given (the laptop's deployable
     catalogue, read in place), its file at the same path must be the same bytes;
  2. the old file is re-proved as E50a's generator proves an entry (`convert.dated_form`: its date put back into its
     undated form gives its bytes, under the creating system its machine recorded), and that proof must equal
     E50a's recorded entry for the file in `tools/content/former_identities.json` (date, system, sha256, undated):
     no relation names a dated file that never existed;
  3. the repaired file is the committed file now (`content/scores/pdmx/<cid>.mxl`), whose sha256 is the row's
     `convertedSha256`;
  4. `restore` is the line hunks that turn the repaired score's text into the old file's undated text, each with
     context until it occurs once in the repaired text;
  5. the relation is re-proved exactly as the build does (`convert.former_identities` with the committed table and
     this relation alone): it must name the old identity, and nothing else.
A row that fails any step stops the run and nothing is written. Output: runs/E50/repaired-identities.txt.
"""
from __future__ import annotations

import difflib
import hashlib
import io
import json
import subprocess
import sys
import zipfile
from pathlib import Path

W = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(W / "tools" / "content"))
import convert  # noqa: E402

OUT = convert.REPAIRED_IDENTITIES_FILE
LOG = W / "docs" / "prompts" / "runs" / "E50" / "repaired-identities.txt"
SEVEN = ["song.pop.margie.pdmx", "song.jazz.django-reinhardt-limehouse-blues.pdmx", "song.blues.singin-the-blues",
         "song.blues.weary-blues", "song.blues.storyville-blues", "song.blues.wabash-blues", "song.blues.tishomingo-blues"]
CHANGE = ("E50 (Entry 163): the opening tempo printed as text (\"= N\") read as the score's metronome mark; the old "
          "file carried the converter's default quarter = 96 beside the printed words")
COMMENT = (
    "E50 (Entry 163): reviewed musical repairs, each relating the old file of a row (an identity E50a's "
    "former_identities.json recorded: a dated file a catalogue able to store a learner's material served) to the "
    "repaired file, for learner continuity only (contact, familiarity, project and encounter lookup; the reviewer's "
    "conditional approval, docs/review/responses/questions-bd7d303e.md section 4). convert.former_identities "
    "re-proves each on every build by rebuilding the old file's bytes from the repaired one (the restore lines put "
    "back, then the date, zipped under the old machine's creating system) and the build records the proved ones in "
    "provenance.formerIdentities beside E50a's. Never an approval, a parentSha256, a pdmx.json field or D2's "
    "exact-byte identity. Generated by docs/prompts/runs/E50/scripts-repaired-identities.py, never edited by hand."
)


def score_entry(raw: bytes, undated: bool) -> tuple[list[tuple[str, bytes]], int]:
    """The archive's entries and the index of its one music21 score (dated or undated, as asked): E50a's own reading."""
    entries = convert._entries(raw)
    at = None if entries is None else convert._score_at(entries, undated=undated)
    if entries is None or at is None:
        raise SystemExit("not a music21 score in the converter's layout")
    return entries, at


def hunks(now: str, was: str) -> list[dict]:
    """Line hunks turning `now` into `was`, each widened by context lines until its `now` occurs once in `now`."""
    a, b = now.splitlines(keepends=True), was.splitlines(keepends=True)
    out: list[dict] = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        for context in range(1, 40):
            lo, hi = max(0, i1 - context), min(len(a), i2 + context)
            left, right = i1 - lo, hi - i2
            snippet_now = "".join(a[lo:hi])
            snippet_was = "".join(a[lo:i1] + b[j1:j2] + a[i2:hi])
            if left + right > 0 and now.count(snippet_now) == 1:
                out.append({"now": snippet_now, "was": snippet_was})
                break
        else:
            raise SystemExit("a hunk that no context makes unique")
    return out


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3) or argv[0] != "--record":
        print(__doc__)
        return 2
    base = argv[1]
    served = Path(argv[2]) if len(argv) == 3 else None
    items = {row["id"]: row for row in json.loads((W / "content/sources/pdmx.json").read_text(encoding="utf-8"))["items"]}
    table = json.loads(convert.FORMER_IDENTITIES_FILE.read_text(encoding="utf-8"))["identities"]
    lines: list[str] = [f"base {base}; served catalogue {served if served else 'not read'}"]
    repairs: list[dict] = []
    for item_id in SEVEN:
        row = items[item_id]
        rel = f"scores/pdmx/{row['cid']}.mxl"
        old = subprocess.run(["git", "-C", str(W), "show", f"{base}:content/{rel}"], capture_output=True, check=True).stdout
        old_sha = hashlib.sha256(old).hexdigest()
        if served is not None:
            laptop = (served / rel).read_bytes()
            if laptop != old:
                raise SystemExit(f"STOP {item_id}: the served catalogue's {rel} is not the committed file at {base}")
        proved = convert.dated_form(old)
        recorded = [e for e in table if e["file"] == rel and e["sha256"] == old_sha]
        if proved is None or len(recorded) != 1 or {k: recorded[0][k] for k in ("date", "system", "sha256", "undated")} != proved:
            raise SystemExit(f"STOP {item_id}: the old file does not re-prove as E50a's entry ({proved} against {recorded})")
        new_path = W / "content" / rel
        new = new_path.read_bytes()
        new_sha = hashlib.sha256(new).hexdigest()
        if new_sha != row["convertedSha256"]:
            raise SystemExit(f"STOP {item_id}: the committed file is not the row's convertedSha256")
        old_entries, old_at = score_entry(old, undated=False)
        new_entries, new_at = score_entry(new, undated=True)
        if [n for n, _ in old_entries] != [n for n, _ in new_entries] or [d for i, (_, d) in enumerate(old_entries) if i != old_at] != [d for i, (_, d) in enumerate(new_entries) if i != new_at]:
            raise SystemExit(f"STOP {item_id}: the archives differ outside the score")
        was = convert.without_encoding_date(old_entries[old_at][1].decode("utf-8"))
        now = new_entries[new_at][1].decode("utf-8")
        repair = {"id": item_id, "file": rel, "change": CHANGE, "from": old_sha, "date": proved["date"], "system": proved["system"],
                  "to": new_sha, "restore": hunks(now, was)}
        named = convert.former_identities(new_path, table, [repair])
        if named != [old_sha]:
            raise SystemExit(f"STOP {item_id}: the relation does not re-prove as the build re-proves it ({named})")
        repairs.append(repair)
        lines.append(f"{item_id}: from {old_sha} ({proved['date']}, system {proved['system']}; E50a's entry re-proved"
                     f"{', the served file identical' if served else ''}) to {new_sha}; {len(repair['restore'])} restore hunk(s), "
                     f"{sum(len(h['was']) for h in repair['restore'])} bytes; re-proved as the build does: named [{old_sha[:12]}]")
    text = json.dumps({"_comment": COMMENT}, indent=2, ensure_ascii=False)[:-2] + ',\n  "repairs": [\n'
    text += ",\n".join("    " + json.dumps(r, ensure_ascii=False) for r in repairs)
    text += "\n  ]\n}\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    lines.append(f"{OUT.relative_to(W).as_posix()}: {len(repairs)} relations, {len(text.encode('utf-8'))} bytes")
    LOG.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
