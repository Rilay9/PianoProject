// Writes build/u125/specs/u66-throttled.spec.ts: engine.spec.ts's U66 test,
// its body copied verbatim from the file at run time, under a beforeEach that
// throttles the page's CPU through the DevTools protocol (U125_CPU_RATE).
// Run from app/.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('tests/e2e/engine.spec.ts', 'utf8').split(/\r?\n/);
const start = src.findIndex((l) => l.includes('is judged in it (U66)'));
let end = start;
// The test ends at the first line after it that is exactly "  });" at its indent.
while (end < src.length && src[end] !== '  });') end += 1;
if (start < 0 || end >= src.length) throw new Error('U66 test not found');
const body = src.slice(start, end + 1).join('\n');

const out = `// Generated by build/u125/make-spec.mjs; the test is engine.spec.ts's U66
// case copied verbatim (lines ${start + 1}-${end + 1}), under CPU throttling.
import { expect, test } from '@playwright/test';
import { openDevScore } from '../../../tests/e2e/fixtures/devScore';

test.describe('Tempo mode end to end', () => {
  // U125_THROTTLE_AT=start (default): throttled from before the page loads.
  // U125_THROTTLE_AT=run: throttled from the harness's startRun on, so the
  // page's setup runs at full speed and the run itself is throttled; the
  // test's body is the same either way.
  // U125_LOG=1: the page's timers logged (as u66-diag.spec.ts does) and, for
  // a failed run, the log and the engine's events written to build/u125/diag/.
  test.afterEach(async ({ page }, info) => {
    if (!process.env.U125_LOG || info.status === info.expectedStatus) return;
    const dump = await page.evaluate(() => ({
      log: (window as unknown as { __u125?: unknown[] }).__u125 ?? [],
      events: window.__pianopathDevScore?.engineEvents() ?? [],
      notes: (window.__pianopathDevScore?.engineScore() as unknown as { notes?: unknown[] } | null)?.notes ?? [],
    }));
    const fs = await import('node:fs');
    fs.mkdirSync('build/u125/diag', { recursive: true });
    fs.writeFileSync(\`build/u125/diag/verbatim-FAIL-\${info.repeatEachIndex}.json\`, JSON.stringify({ error: info.error?.message, ...dump }));
  });

  test.beforeEach(async ({ page }) => {
    if (process.env.U125_LOG) {
      await page.addInitScript(() => {
        const log: [string, number, number, string?][] = [];
        (window as unknown as { __u125: typeof log }).__u125 = log;
        const now = () => performance.now();
        let seenEv = 0;
        const ev = (): string => {
          const h = (window as unknown as { __pianopathDevScore?: { engineEvents?: () => { kind: string; step?: number }[] } }).__pianopathDevScore;
          const all = h?.engineEvents?.() ?? [];
          if (all.length < seenEv) seenEv = 0;
          const fresh = all.slice(seenEv).map((e) => e.kind + (e.step ?? '')).join(',');
          seenEv = all.length;
          return fresh;
        };
        const st = window.setTimeout.bind(window);
        window.setTimeout = ((fn: () => void, ms?: number, ...rest: unknown[]) => {
          const at = now();
          const d = ms ?? 0;
          return st(() => {
            if (d >= 50) log.push([\`to\${d}\`, at + d, now()]);
            fn(...(rest as []));
            if (d >= 50) log.push([\`to\${d}:end\`, at + d, now(), ev()]);
          }, ms);
        }) as typeof window.setTimeout;
        const si = window.setInterval.bind(window);
        window.setInterval = ((fn: () => void, ms?: number) =>
          si(() => {
            const t = now();
            fn();
            log.push(['iv', t, now(), ev()]);
          }, ms)) as typeof window.setInterval;
        const raf = window.requestAnimationFrame.bind(window);
        window.requestAnimationFrame = ((fn: FrameRequestCallback) =>
          raf((ts) => {
            const t = now();
            fn(ts);
            log.push(['raf', t, now(), ev()]);
          })) as typeof window.requestAnimationFrame;
      });
    }
    const rate = Number(process.env.U125_CPU_RATE ?? '1');
    if (rate <= 1) return;
    const cdp = await page.context().newCDPSession(page);
    if (process.env.U125_THROTTLE_AT !== 'run') {
      await cdp.send('Emulation.setCPUThrottlingRate', { rate });
      return;
    }
    await page.exposeBinding('__u125Throttle', () => cdp.send('Emulation.setCPUThrottlingRate', { rate }));
    await page.addInitScript(() => {
      const w = window as unknown as Record<string, unknown>;
      let handle: unknown;
      Object.defineProperty(window, '__pianopathDevScore', {
        configurable: true,
        get: () => handle,
        set: (v: { startRun?: (...a: unknown[]) => unknown } | undefined) => {
          if (v && typeof v.startRun === 'function') {
            const original = v.startRun;
            v.startRun = (...a: unknown[]) => {
              void (w.__u125Throttle as () => Promise<void>)();
              return original(...a);
            };
          }
          handle = v;
        },
      });
    });
  });

${body}
});
`;
writeFileSync('build/u125/specs/u66-throttled.spec.ts', out);
console.log(`copied lines ${start + 1}-${end + 1}`);
